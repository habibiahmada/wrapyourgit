/**
 * Writes the art the README badges carry inside them (ADR-0035). A README image is an <img>,
 * which loads nothing from inside an SVG, so it has to travel as data URLs:
 *
 * - apps/web/src/badge/archetype-art.ts: each archetype's diorama for the card, trimmed, scaled
 *   down and encoded as WebP. WebP rather than AVIF: these images show wherever GitHub shows a
 *   README, apps and webviews included.
 * - apps/web/src/badge/language-icons.ts: the Devicon logos in packages/video/public/lang, as SVG.
 *   The ones drawn in plain black (no fill of their own) are given the badge's text colour, or
 *   they would vanish on its dark ground.
 *
 *   bun scripts/badge-art.ts
 */

import { dirname, join, resolve } from "node:path";
import { archetypeIdSchema } from "@wyg/schema";

const root = resolve(import.meta.dir, "..");
const artDir = join(root, "packages/video/public/art");
const out = join(root, "apps/web/src/badge/archetype-art.ts");
const langDir = join(root, "packages/video/public/lang");
const langOut = join(root, "apps/web/src/badge/language-icons.ts");
/** The badge's FG (badge.ts), for logos with no colour of their own. */
const INK_ON_DARK = "#eeeae0";
// sharp is Next's optional dependency, so it resolves from the web app, not from the root.
const next = Bun.resolveSync("next/package.json", join(root, "apps/web"));
const sharp = (await import(Bun.resolveSync("sharp", dirname(next)))).default;

/** Twice the width the card draws, so it stays sharp on dense screens: about 20 KB each. */
const DIORAMA_WIDTH = 360;

async function encode(file: string, resize: { width?: number; height?: number }) {
  const { data, info } = await sharp(join(artDir, file))
    .trim()
    .resize({ ...resize, kernel: "lanczos3" })
    .webp({ quality: 78, alphaQuality: 90, effort: 6 })
    .toBuffer({ resolveWithObject: true });
  return {
    href: `data:image/webp;base64,${data.toString("base64")}`,
    width: info.width,
    height: info.height,
    bytes: data.length,
  };
}

/**
 * The dashboard's moving diorama (#211): a still base and an animated overlay of the parts that
 * move, both on the full canvas the still is drawn on. They are scaled, not trimmed (sharp would
 * have to crop every frame), so the card crops them in SVG to the box the still was trimmed to.
 */
async function encodeMotion(id: string) {
  const webp = (file: string, animated: boolean, quality: number) =>
    sharp(join(artDir, file), { animated })
      .resize({ width: DIORAMA_WIDTH, kernel: "lanczos3" })
      .webp({ quality, alphaQuality: 85, effort: 6, loop: 0 })
      .toBuffer({ resolveWithObject: true });
  const base = await webp(`skin-${id}-base.webp`, false, 78);
  const frames = await webp(`skin-${id}.webp`, true, 70);
  // Where the still's trim found the diorama, in the still's own pixels.
  const source = await sharp(join(artDir, `skin-${id}.png`)).metadata();
  const trimmed = await sharp(join(artDir, `skin-${id}.png`))
    .trim()
    .toBuffer({ resolveWithObject: true });
  const scale = DIORAMA_WIDTH / (source.width ?? DIORAMA_WIDTH);
  const round = (n: number) => Math.round(n * scale * 100) / 100;
  return {
    base: `data:image/webp;base64,${base.data.toString("base64")}`,
    frames: `data:image/webp;base64,${frames.data.toString("base64")}`,
    width: base.info.width,
    height: base.info.height,
    crop: {
      x: round(-(trimmed.info.trimOffsetLeft ?? 0)),
      y: round(-(trimmed.info.trimOffsetTop ?? 0)),
      width: round(trimmed.info.width),
      height: round(trimmed.info.height),
    },
    bytes: base.data.length + frames.data.length,
    pages: frames.info.pages ?? 1,
  };
}

const entries: string[] = [];
for (const id of archetypeIdSchema.options) {
  const diorama = await encode(`skin-${id}.png`, { width: DIORAMA_WIDTH });
  const motion = await encodeMotion(id);
  console.log(
    `${id}: diorama ${diorama.width}x${diorama.height} ${Math.round(diorama.bytes / 1024)} KB, motion ${motion.pages} frames ${Math.round(motion.bytes / 1024)} KB`,
  );
  const pick = ({ href, width, height }: typeof diorama) => ({ href, width, height });
  const { base, frames, width, height, crop } = motion;
  entries.push(
    `  ${JSON.stringify(id)}: ${JSON.stringify({ diorama: pick(diorama), motion: { base, frames, width, height, crop } })},`,
  );
}

await Bun.write(
  out,
  `// Generated by scripts/badge-art.ts from packages/video/public/art. Do not edit by hand.
import type { ArchetypeId } from "@wyg/schema";

export interface BadgeImage {
  href: string;
  width: number;
  height: number;
}

/**
 * The moving diorama: a still base and an animated overlay on the full canvas, and the box (in
 * that canvas's pixels) the still diorama was trimmed to, so both can be cropped to match it.
 */
export interface BadgeMotion {
  base: string;
  frames: string;
  width: number;
  height: number;
  crop: { x: number; y: number; width: number; height: number };
}

export const ARCHETYPE_ART: Record<ArchetypeId, { diorama: BadgeImage; motion: BadgeMotion }> = {
${entries.join("\n")}
};
`,
);
console.log(`wrote ${out}`);

const icons: string[] = [];
const glob = new Bun.Glob("*.svg");
for (const file of [...glob.scanSync(langDir)].sort()) {
  let svg = (await Bun.file(join(langDir, file)).text()).trim();
  // A logo with no fill anywhere is drawn in the default black: colour it from the root.
  if (!/fill[=:]/.test(svg)) svg = svg.replace("<svg ", `<svg fill="${INK_ON_DARK}" `);
  const slug = file.replace(/\.svg$/, "");
  icons.push(
    `  ${JSON.stringify(slug)}: "data:image/svg+xml;base64,${Buffer.from(svg).toString("base64")}",`,
  );
}
await Bun.write(
  langOut,
  `// Generated by scripts/badge-art.ts from packages/video/public/lang. Do not edit by hand.

/** Devicon logos by file slug (languageIcon), as data URLs. See public/lang/LICENSES.md. */
export const LANGUAGE_ICONS: Record<string, string> = {
${icons.join("\n")}
};
`,
);
console.log(`wrote ${langOut} (${icons.length} logos)`);
